package com.solorecord.app

fun main() {
    val m = RecordingStateMachine()
    check(!m.send(CaptureEvent.PAUSE))
    check(m.send(CaptureEvent.START))
    check(!m.send(CaptureEvent.START))
    check(m.send(CaptureEvent.READY))
    check(m.send(CaptureEvent.PAUSE))
    check(!m.send(CaptureEvent.PAUSE))
    check(m.send(CaptureEvent.RESUME))
    check(m.send(CaptureEvent.STOP))
    check(m.send(CaptureEvent.FINISH))
    check(m.state == CaptureState.IDLE)
    val unexpected = RecordingStateMachine()
    check(unexpected.send(CaptureEvent.START))
    check(unexpected.send(CaptureEvent.STOP))
    check(!unexpected.send(CaptureEvent.READY))
    check(unexpected.send(CaptureEvent.FINISH))
    check(RecordingPolicy.videoSize(1080,2400,1920) == VideoSize(864,1920))
    check(RecordingPolicy.videoSize(2400,1080,1920) == VideoSize(1920,864))
    check(RecordingPolicy.videoSize(720,1280,1920) == VideoSize(720,1280))
    check(RecordingPolicy.videoSize(719,1279,1280) == VideoSize(704,1264))
    check(RecordingPolicy.bitrate(VideoSize(320,320),30) == 2_000_000)
    check(RecordingPolicy.bitrate(VideoSize(3840,2160),60) == 14_000_000)
    check(RecordingPolicy.safePrefix("My Record") == "My_Record")
    check(RecordingPolicy.safePrefix("hack/../evil") == "hack____evil")
    check(RecordingPolicy.safePrefix("...") == "SoloRecord")
    check(RecordingPolicy.safePrefix("a".repeat(100)).length == 24)
    println("PASS: 19 JVM smoke assertions across lifecycle, scaling, bitrate, filename safety")
}
